def s2t(text):
    if not text:
        return text
    # First apply phrase mappings
    res = text
    for p_s, p_t in PHRASE_MAPPINGS.items():
        res = res.replace(p_s, p_t)
    # Then character mappings
    return ''.join(CHAR_MAPPINGS.get(ch, ch) for ch in res)
